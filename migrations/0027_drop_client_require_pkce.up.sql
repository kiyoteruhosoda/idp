-- 参照されていない設定 `clients.require_pkce` を削除する（SEC12）。
--
-- この列は登録 API・管理コンソールのチェックボックスとして露出していたが、`/authorize` からも
-- `/token` からも**一度も読まれていなかった**。PKCE（S256）は client_type によらず無条件に
-- 要求されるため、実際の挙動は列の値に関わらず「常に必須」で、画面は「切れる」と誤解させる
-- 表示になっていた。
--
-- 「実装する（列に従って PKCE を任意化する）」ではなく「削除する」を選んだのは、PKCE を切れる
-- 設定は認可コード横取り攻撃（RFC 7636 §1）への防御を落とす操作であり、OAuth 2.1 が全クライアントに
-- PKCE を要求する方向と逆行するため。設定として存在しなければ、誤って切られることも無い。
ALTER TABLE clients DROP COLUMN require_pkce;
