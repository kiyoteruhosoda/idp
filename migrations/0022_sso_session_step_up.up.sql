-- Step-up 認証の記録（AP5。ユーザー認証・認証ポリシー仕様書 §15）。
--
-- 重要操作（パスワード変更・認証器の追加削除・外部 IdP の紐付け）の直前に本人確認を通した時刻。
-- ログイン時刻（`auth_time`）とは別に持つ必要がある: `auth_time` は SSO セッションの起点で、
-- 復元（サイレント再認証）では更新されない ＝ 8 時間前のログインでもずっと同じ値のままになる。
-- 「今この操作をしてよいと確認できているか」はそれとは別の新しさで測る。
--
-- 第二要素の鮮度は AP4 で入れた `mfa_completed_at` が担うため、ここでは単一要素の再確認だけを
-- 記録すればよい（多要素を要求する操作の判定は `mfa_completed_at` を見る）。
ALTER TABLE sso_sessions
    ADD COLUMN step_up_at DATETIME(6) NULL
        COMMENT '重要操作の直前に本人確認（step-up）を通した時刻。NULL = ログイン以降 step-up していない';
