-- TOTP コードの再利用（リプレイ）を防ぐための、直近に受理した time-step の記録。
--
-- これまで TOTP の検証は `totp-rs` の検証（skew=1・step=30 秒）を通すだけで、**受理したコードを
-- 消費済みとして残していなかった**。そのため、いちど正しく提示された 6 桁は、有効な時間窓
-- （最大 ~90 秒）の間は別セッション・別 IP からでも何度でも通った（RFC 6238 §5.2 は使用済み
-- コードの再受理を禁じている）。リアルタイムのフィッシング代理や盗み見で 1 コードを掴まれると、
-- その窓の間は第二要素を突破できる。
--
-- 受理した time-step（= unix 秒 / 30）を記録し、**同じか古いステップのコードは以後受理しない**。
-- リカバリーコード・email OTP・SMS OTP は既に 1 回きりで消費するため、この列は TOTP 専用である。
--
-- ⚠ NULL は「まだ一度も受理していない」を表す（本列の導入前から在る行を含む）。読み出し側は
--    NULL を「どのステップより新しくてもよい」として扱う。
ALTER TABLE user_authenticators
    ADD COLUMN totp_last_used_step BIGINT NULL
        COMMENT '直近に受理した TOTP の time-step（unix 秒 / 30）。同じか古いステップのコードは再受理しない（リプレイ対策）。TOTP 以外の種別では NULL';
