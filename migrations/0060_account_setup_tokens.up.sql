-- アカウント設定のワンタイムリンク（ADR-0062）。
--
-- 管理者が利用者を作った直後・パスワードを再発行した直後に渡す「1 回だけ開けるリンク」を、
-- 既に在るパスワード再設定のトークン（MT18）と同じ表で扱う。どちらも「トークンの所持を本人性の
-- 根拠にして資格情報を決めさせる」もので、違うのは**リンク先で何をさせるか**だけである。
-- 表を分けると、消費・失効・期限切れの判定が 2 本になり、片方だけ直す事故が起きる。
--
-- purpose:
--   reset  … 本人が要求したパスワード再設定（従来。既定値なので既存行はすべてこれになる）
--   setup  … 管理者が発行したアカウント設定（パスワードの設定に加えてパスキーの登録も許す）
--
-- ⚠ パスキーの登録を許すのは `setup` だけである。`reset` は「パスワードを忘れた」経路なので、
--   そこに認証器を足せると、メールを一時的に読める相手が居座る手段を得てしまう。
ALTER TABLE password_reset_tokens
    ADD COLUMN purpose VARCHAR(16) NOT NULL DEFAULT 'reset'
        COMMENT 'リンクの用途（reset = 本人の再設定 / setup = 管理者が発行したアカウント設定）',
    ADD CONSTRAINT password_reset_tokens_purpose_chk
        CHECK (purpose IN ('reset', 'setup'));
